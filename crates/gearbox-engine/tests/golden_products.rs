//! Golden outputs of the repository's products (test case G0).
//!
//! Every profile of every product in `products/` is resolved and generated in
//! memory, and the files that decide what gets built and deployed -- the lock,
//! the Cargo manifests, the runtime configuration and the Helm chart -- are
//! compared with a recorded golden under `tests/golden/`. Version and source
//! fingerprint noise is normalized away, so a diff is a change in composition,
//! linkage, configuration or deployment.
//!
//! This is the compatibility check for Phase 2B of the service-deployment
//! roadmap (Gearbox ADR-0026, "Consequences"): a product that does not opt into
//! the new dependency model must generate the same output. After an intended
//! change, re-record with `GEARBOX_BLESS=1 cargo test -p gearbox-engine --test
//! golden_products` and review the golden diff like any other.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    reason = "clippy.toml's allow-unwrap-in-tests covers #[test] fns but not the helpers here"
)]

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use gearbox_engine::generate::{GenerateInput, TemplateSet, generate};
use gearbox_engine::{SourceRoot, load_catalogue, load_product};
use gearbox_ir::{FileEntry, SourceId};

#[path = "common/corpus.rs"]
mod corpus_support;

const PRODUCTS: &[&str] = &["payments-demo", "configurable-gears", "integration-demo"];

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("the repository containing this test")
}

fn golden_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/golden")
}

/// Whether a generated file is part of the golden: the lock, Cargo manifests,
/// runtime configuration and the Helm chart.
fn kept(path: &str) -> bool {
    path == "product.lock"
        || path.ends_with("Cargo.toml")
        || (path.starts_with("config/")
            && Path::new(path)
                .extension()
                .is_some_and(|ext| ext.eq_ignore_ascii_case("yaml")))
        || path.starts_with("helm/")
}

/// Remove what changes without the composition changing: digests, the gearbox
/// version, and where the source checkout and the output tree happen to live.
fn normalize(text: &str, source_root: &Path, out_root: &Path) -> String {
    let source = source_root.to_string_lossy().into_owned();
    let out = out_root.to_string_lossy().into_owned();
    let mut normalized = String::with_capacity(text.len());
    for line in text.lines() {
        let mut line = line
            .replace(&source, "<gears-rust>")
            .replace(&out, "<out>")
            .replace(&repo().to_string_lossy().into_owned(), "<repo>");
        // `blake3:<64 hex>` digests and lock hashes.
        while let Some(start) = line.find("blake3:") {
            let digest_start = start + "blake3:".len();
            let end = line[digest_start..]
                .find(|c: char| !c.is_ascii_hexdigit())
                .map_or(line.len(), |offset| digest_start + offset);
            if end == digest_start {
                break;
            }
            line.replace_range(start..end, "<digest>");
        }
        // Relative paths from the output tree to the checkout: `../../..` chains
        // that end in the source root's directory name.
        if let Some(name) = source_root.file_name().and_then(|n| n.to_str()) {
            let marker = format!("/{name}/");
            while let Some(pos) = line.find(&marker) {
                let begin = line[..pos]
                    .rfind(['"', '\'', ' ', '='])
                    .map_or(0, |i| i + 1);
                if !line[begin..pos].chars().all(|c| c == '.' || c == '/') {
                    break;
                }
                line.replace_range(begin..pos + marker.len(), "<gears-rust>/");
            }
        }
        if line.contains("gearbox_version") || line.contains("GENERATED by gearbox") {
            line = line.replace(env!("CARGO_PKG_VERSION"), "<version>");
        }
        normalized.push_str(&line);
        normalized.push('\n');
    }
    normalized
}

/// Every profile of `product`, resolved and generated, as one normalized text.
fn render(product: &str) -> Option<BTreeMap<String, String>> {
    let root = corpus_support::root()?;
    let opened = vec![SourceRoot::open(SourceId::new("gears-rust").unwrap(), &root).unwrap()];
    let scan = load_catalogue(&opened);
    let path = repo().join("products").join(product).join("product.gdl");
    let loaded = load_product(&path, None);
    let intent = loaded.intent.expect("the product evaluates");
    let source_roots: BTreeMap<SourceId, PathBuf> = opened
        .iter()
        .map(|r| (r.id.clone(), r.root.clone()))
        .collect();

    let mut per_profile = BTreeMap::new();
    for profile in intent.profiles.keys() {
        let resolution =
            gearbox_engine::resolve::resolve_at(&scan.catalogue, &intent, profile, Some(&path));
        let sources = opened
            .iter()
            .map(|r| (r.id.clone(), r.to_resolved()))
            .collect();
        let lock = gearbox_engine::resolve::product::assemble(
            &scan.catalogue,
            &intent,
            &resolution,
            sources,
        );
        let out_root = repo().join(".gearbox").join(product).join(profile.as_str());

        let mut text = String::new();
        // Errors decide whether anything is generated, so they are part of it.
        let mut errors: Vec<String> = resolution
            .diagnostics
            .iter()
            .filter(|d| d.severity == gearbox_ir::Severity::Error)
            .map(|d| format!("{} {}", d.code.as_str(), d.message))
            .collect();
        errors.sort();
        for error in &errors {
            writeln!(text, "!!! {error}").unwrap();
        }
        match generate(&GenerateInput {
            lock: &lock,
            source_roots: &source_roots,
            out_root: &out_root,
            templates: TemplateSet::new(),
            // The UI composition reads the product's npm lock from here.
            product_dir: path.parent(),
            catalogue: None,
            registry: None,
        }) {
            Ok(generated) => {
                let mut files: Vec<(&str, &FileEntry)> = generated
                    .files
                    .iter()
                    .map(|entry| (entry.path.as_str(), entry))
                    .filter(|(path, _)| kept(path))
                    .collect();
                files.sort_by_key(|(path, _)| *path);
                for (path, entry) in files {
                    writeln!(text, "=== {path}").unwrap();
                    text.push_str(&normalize(
                        entry.as_text().unwrap_or("<binary>"),
                        &root,
                        &out_root,
                    ));
                }
            }
            Err(err) => writeln!(text, "!!! generation failed: {err}").unwrap(),
        }
        per_profile.insert(profile.as_str().to_owned(), text);
    }
    Some(per_profile)
}

#[test]
fn products_generate_their_recorded_golden_output() {
    let bless = std::env::var_os("GEARBOX_BLESS").is_some();
    let mut drifted = Vec::new();
    for product in PRODUCTS {
        let Some(rendered) = render(product) else {
            eprintln!("skipping: gears-rust not present");
            return;
        };
        for (profile, text) in rendered {
            let golden = golden_dir().join(format!("{product}.{profile}.txt"));
            if bless {
                std::fs::create_dir_all(golden_dir()).unwrap();
                std::fs::write(&golden, &text).unwrap();
                continue;
            }
            let recorded = std::fs::read_to_string(&golden).unwrap_or_default();
            if recorded != text {
                let first = recorded
                    .lines()
                    .zip(text.lines())
                    .position(|(a, b)| a != b)
                    .unwrap_or_else(|| recorded.lines().count().min(text.lines().count()));
                drifted.push(format!(
                    "{}: first difference at line {} (re-record with GEARBOX_BLESS=1 and review the diff)",
                    golden.display(),
                    first + 1
                ));
            }
        }
    }
    assert!(drifted.is_empty(), "golden drift:\n{}", drifted.join("\n"));
}
